/**
 * Search shorthands customers type: "S24U", "15PM", "13R+"… Derived from the model name with the brand-style
 * prefix dropped ("Galaxy", "iPhone", "Pixel", the brand itself) and spaces removed.
 */
export function phoneAliases(brand: string, name: string): string[] {
  const base = name
    .toLowerCase()
    .replace(new RegExp(`^(${brand.toLowerCase()}|galaxy|iphone|pixel|redmi|moto)\\s+`), "")
    .replace(/[()]/g, "");
  const short = base.replace(/ pro max/g, "pm").replace(/ ultra/g, "u").replace(/ plus/g, "+").replace(/\s+/g, "");
  const compact = base.replace(/\s+/g, "");
  return [...new Set([compact, short])].filter((a) => a.length >= 2 && a !== name.toLowerCase());
}
